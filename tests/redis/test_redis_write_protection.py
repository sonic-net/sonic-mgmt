"""Acceptance checks for local Redis write protection."""
import json
from pathlib import Path
import shlex

import pytest

pytestmark = [pytest.mark.topology('any')]


def test_redis_enforce_mode(duthosts, loganalyzer, request):
    if request.config.getoption('--redis-protection-mode') == 'legacy':
        pytest.skip('Protected acceptance requires the enforce test plan')
    assert list(duthosts), 'Protected acceptance requires at least one DUT'
    for duthost in duthosts:
        check_protected_dut(duthost, loganalyzer, request)


def check_protected_dut(duthost, loganalyzer, request):
    if not duthost.stat(path='/run/redis-auth/local.json')['stat']['exists']:
        if request.config.getoption('--redis-protection-mode') == 'enforce':
            pytest.fail('Required Redis protection is not active on ' + duthost.hostname)
        pytest.skip('Redis write protection is not enabled on this image')
    # Expect only the SET denials generated by this probe's scratch keys.
    if loganalyzer:
        for program in ('python3', 'sonic-db-cli'):
            loganalyzer[duthost.hostname].expect_regex.append(
                r'.*ERR ' + program + r': .*RedisReply catches system_error: '
                r'command: .*SET.*__sonic_redis_access_test__:[0-9a-f]{32}'
                r'.*forbidden.*reason: NOPERM User default has no permissions '
                r"to run the 'set' command: Input/output error.*"
            )
    directory = duthost.tempfile(state='directory', prefix='redis-access-')['path']
    try:
        duthost.file(path=directory, mode='0755')
        destination = directory + '/check_redis_access.py'
        source = Path(__file__).parent / 'files/check_redis_access.py'
        duthost.copy(src=str(source), dest=destination, mode='0755')
        mixed = request.config.getoption('--redis-allow-tcp-exceptions')
        command = 'python3 ' + shlex.quote(destination) + (' --allow-tcp-exceptions' if mixed else '')
        result = duthost.command(command, module_ignore_errors=True)
        assert result['rc'] == 0, result['stdout'] + result.get('stderr', '')
        report = json.loads(result['stdout'])
        assert report['success'] and report['protected_processes_verified'], report
        if mixed:
            assert report['mode'] == 'mixed' and report['unprotected_processes'], report
            assert report['security_verified'] is False, report
        else:
            assert report['security_verified'], report
            assert report['protected_databases'] == report['admin_databases_checked'], report
        assert report['ordinary_databases_checked'] == report['protected_databases'] > 0, report
        assert report['named_databases_checked'] > 0, report
        expected = int(duthost.facts.get('num_asic', 1))
        namespaces = [''] + (['asic' + str(index) for index in range(expected)] if expected > 1 else [])
        assert report['namespaces'] == sorted(namespaces), report
        assert report['actual_redis_processes_checked'] == len(report['processes']) > 0, report
    finally:
        duthost.file(path=directory, state='absent')
