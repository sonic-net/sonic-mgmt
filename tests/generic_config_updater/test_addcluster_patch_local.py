def _make_full_config(no_t1, reference_ops, with_autogen_lossless=True):
    """Device state with the T1 present: reference patch applied, plus side effects."""
    import copy

    import jsonpatch

    full = jsonpatch.JsonPatch(reference_ops).apply(copy.deepcopy(no_t1))
    if with_autogen_lossless:
        # The buffer manager creates the lossless PG on link-up. It is never part of
        # the pushed config, so it must not appear in a generated patch either.
        full["BUFFER_PG"]["{}|3-4".format(PORT)] = {"profile": "pg_lossless_100000_500m_profile"}
    return full


def _write(tmp_path, name, config):
    path = os.path.join(str(tmp_path), name)
    with open(path, "w") as f:
        json.dump(config, f, indent=2)
    return path


def _build_configs(tmp_path, with_autogen_lossless=True):
    reference = _load_reference()
    no_t1 = _make_no_t1_config()
    full = _make_full_config(no_t1, reference, with_autogen_lossless)

    full_path = _write(tmp_path, "full.json", full)
    no_t1_path = _write(tmp_path, "no_t1.json", no_t1)
    return reference, full_path, no_t1_path


def _generate(tmp_path, buffer_model=None, with_autogen_lossless=True):
    reference, full_path, no_t1_path = _build_configs(tmp_path, with_autogen_lossless)

    patch_file, = generate_config_patch(full_path, no_t1_path, buffer_model=buffer_model)
    with open(patch_file) as f:
        return reference, json.load(f)


def _generate_with_config(tmp_path, buffer_model=None, with_autogen_lossless=True):
    """Same as _generate, but returns the target config path instead of the reference."""
    _, full_path, no_t1_path = _build_configs(tmp_path, with_autogen_lossless)

    patch_file, = generate_config_patch(full_path, no_t1_path, buffer_model=buffer_model)
    with open(patch_file) as f:
        return full_path, json.load(f)


class TestAddClusterPatchContent:
    """What a generated add-cluster patch must and must not carry."""

    def test_buffer_and_queue_tables_present(self, tmp_path):
        """Traditional buffer platforms need BUFFER_PG/BUFFER_QUEUE/QUEUE in the patch.

        The buffer manager does not derive these, so a port added without them comes
        up with default buffering and no PFC.
        """
        _, generated = _generate(tmp_path)
        tables = {op["path"].split("/")[1] for op in generated}

        for table in ("BUFFER_PG", "BUFFER_QUEUE", "QUEUE"):
            assert table in tables, "{} missing from generated patch".format(table)

    def test_autogenerated_lossless_pg_excluded(self, tmp_path):
        """The lossless PG is created by the buffer manager, never pushed.

        Its profile name encodes port speed and cable length, so a pushed entry would
        reference a profile that may not exist at apply time.
        """
        _, generated = _generate(tmp_path)

        lossless = [
            op for op in generated
            if op["path"].startswith("/BUFFER_PG/") and "3-4" in op["path"]
        ]
        assert not lossless, "Auto-generated lossless BUFFER_PG leaked into patch: {}".format(lossless)

    def test_acl_bindings_are_appends(self, tmp_path):
        """Pre-existing ACL tables must be extended, not replaced."""
        _, generated = _generate(tmp_path)

        acl_ops = [op for op in generated if op["path"].startswith("/ACL_TABLE/")]
        assert acl_ops, "Expected ACL_TABLE bindings in patch"

        for op in acl_ops:
            assert op["path"].endswith("/ports/-"), \
                "Expected append op for pre-existing ACL table, got: {}".format(op)
            assert op["value"] == LAG


class TestMirrorAclPortExtraction:
    """The test's ACL verification must understand the patch format the generator emits.

    If these drift apart, acl_bound_ports comes out empty and the hardware test
    silently skips MIRROR ACL verification instead of failing.
    """

    def test_extracts_ports_from_append_ops(self, tmp_path):
        full_path, generated = _generate_with_config(tmp_path)

        ports = extract_mirror_acl_ports(generated, full_path)

        assert ports == {LAG}, \
            "Append-form ACL bindings must be extracted, got: {}".format(ports)

    def test_extracts_ports_from_whole_entry_add(self, tmp_path):
        full_path, _ = _generate_with_config(tmp_path)
        patch = [{
            "op": "add",
            "path": "/ACL_TABLE/NEW_MIRROR",
            "value": {"type": "MIRROR", "stage": "ingress", "ports": [LAG, PORT]},
        }]

        assert extract_mirror_acl_ports(patch, full_path) == {LAG, PORT}

    def test_ignores_non_mirror_acl_tables(self, tmp_path):
        full_path, _ = _generate_with_config(tmp_path)
        patch = [{
            "op": "add",
            "path": "/ACL_TABLE/DATAACL",
            "value": {"type": "L3", "stage": "ingress", "ports": [LAG]},
        }]

        assert extract_mirror_acl_ports(patch, full_path) == set()

    def test_ignores_backplane_ports(self, tmp_path):
        full_path, _ = _generate_with_config(tmp_path)
        patch = [{
            "op": "add",
            "path": "/ACL_TABLE/EVERFLOW/ports/-",
            "value": "Ethernet-BP256",
        }]

        assert extract_mirror_acl_ports(patch, full_path) == set()

    def test_no_acl_ops_yields_empty_set(self, tmp_path):
        full_path, _ = _generate_with_config(tmp_path)
        patch = [{"op": "add", "path": "/PORT/{}".format(PORT), "value": {"admin_status": "up"}}]

        assert extract_mirror_acl_ports(patch, full_path) == set()


class TestBufferModelHandling:
    """Buffer/queue tables are only valid on traditional buffer platforms."""

    def test_dynamic_buffer_model_excludes_buffer_tables(self, tmp_path):
        _, generated = _generate(tmp_path, buffer_model="dynamic")
        tables = {op["path"].split("/")[1] for op in generated}

        for table in ("BUFFER_PG", "BUFFER_QUEUE", "QUEUE"):
            assert table not in tables, \
                "{} must not be pushed on dynamic buffer platforms".format(table)

    def test_detects_dynamic_from_device_metadata(self):
        config = {"DEVICE_METADATA": {"localhost": {"buffer_model": "dynamic"}}}
        assert get_buffer_model(config, is_multi_asic=False) == "dynamic"

    def test_defaults_to_traditional_when_unset(self):
        config = {"DEVICE_METADATA": {"localhost": {"hwsku": "Arista-7060X6"}}}
        assert get_buffer_model(config, is_multi_asic=False) == "traditional"

    def test_detects_dynamic_in_multi_asic(self):
        config = {"asic0": {"DEVICE_METADATA": {"localhost": {"buffer_model": "dynamic"}}}}
        assert get_buffer_model(config, is_multi_asic=True) == "dynamic"


class TestAutogeneratedBufferPgDetection:
    """Only buffer-manager-generated lossless profiles are filtered."""

    def test_entry_level_lossless_detected(self):
        assert is_autogenerated_buffer_pg(
            "BUFFER_PG", None, {"profile": "pg_lossless_100000_500m_profile"}
        )

    def test_property_level_lossless_detected(self):
        assert is_autogenerated_buffer_pg("BUFFER_PG", "profile", "pg_lossless_40000_5m_profile")

    def test_lossy_profile_not_filtered(self):
        assert not is_autogenerated_buffer_pg(
            "BUFFER_PG", None, {"profile": "ingress_lossy_profile"}
        )

    def test_other_tables_not_filtered(self):
        assert not is_autogenerated_buffer_pg(
            "BUFFER_QUEUE", None, {"profile": "egress_lossless_profile"}
        )
