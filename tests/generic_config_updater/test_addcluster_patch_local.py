"""Hardware-free tests for add-cluster patch generation.

These exercise the decisions the generator makes about *what belongs in the patch*:
which buffer tables are valid for the platform's buffer model, which BUFFER_PG
entries are created by the buffer manager rather than pushed, and how ports are
bound to pre-existing ACL tables.

Every check here runs against a realistic whole-device config built by applying the
reference add-cluster patch to a device state with the T1 removed. Per-case snippets
would drift towards whatever the code already does; a full config will not.

Run: pytest --noconftest tests/generic_config_updater/test_addcluster_patch_local.py -v
"""
