# flake8: noqa: F403, F401, F405
"""
Test Case 5 - PFC propagation for RoCEv2/RDMA AI/storage traffic.

Objective:
    Validate basic PFC propagation. When the tester generates PFC pause on the
    receiver ports, the DUT must propagate PFC upstream to the senders on the same
    lossless priorities, while keeping the lossless traffic loss-free. Roles
    T0/T1/T2.

Topology:
    Test Topology 1 (single DUT, 4 TGEN ports). Point-to-point, 1 rank per port:
        rank0 -> rank2 on lossless Q3 (DSCP 3)
        rank1 -> rank3 on lossless Q4 (DSCP 4)
    The DUT is expected to have Q3/Q4 lossless with PFC + ECN-marking enabled
    (testbed qos config).

Traffic (per the test plan):
    RoCEv2 storage traffic, 4K IB MTU, 128 KB messages (32 packets/message),
    non-ECT (ECN-CE bits 00 -> no ECN marking, so congestion drives PFC), 100%
    line rate per Tx port.

Phases (parametrized as `phase`, mirroring plan steps 4 and 6):
    baseline (10s, no tester pause):
        no congestion -> all messages complete, no loss, no NAK/sequence errors,
        and NO PFC generated by the DUT on Q3/Q4.
    pfc_gen  (30s, tester generates PFC on rank2/rank3 for 90% bandwidth):
        the DUT propagates PFC upstream -> all messages still complete, no loss,
        no NAK/sequence errors, and PFC IS generated by the DUT on Q3/Q4.

NOTES:
    * PFC is measured from the authoritative DUT Tx PFC counter; the snappi
      Rx-pause port stat is unreliable, so the tester counter is logged only.
    * ACK/NAK DSCP is taken from the DUT DSCP->TC map (priority_to_dscp[6]),
      not hardcoded to 48 (the plan's 48 is testbed-specific).
    * Step 5 (tester-side PFC generation) is isolated behind generate_tester_pfc()
      and is NOT implemented yet - the pfc_gen phase skips until it lands.
"""
import pytest
import logging

from snappi_tests.rocev2.files.helper import *   # lib + re-exported fixtures
from tests.common.snappi_tests.qos_fixtures import disable_pfcwd   # noqa: F401

logger = logging.getLogger(__name__)

pytestmark = [pytest.mark.topology('multidut-tgen', 'tgen')]

BASELINE_DURATION = 10     # seconds (plan step 4)
PAUSE_DURATION = 30        # seconds (plan step 6)
IB_MTU = 4096              # 4K IB MTU
MSG_SIZE_KB = 128          # 128KB message (~32 packets/message at 4K MTU)
LINE_RATE_PCT = 100        # % - each Tx sends at full rate
# Per-ECN tester pause bandwidth, passed to generate_tester_pfc as bw_pct (the tester's
# ConsumptionRate, % of line rate). Plan-update values: ect_1 pauses harder (10), non_ect
# lighter (50).
PAUSE_BW_PCT = {"ect_1": 10, "non_ect": 50}
ACK_QUEUE = 6              # ACK/NAK control queue; DSCP from the DUT DSCP->TC map
CNP_QUEUE = 5              # CNP control queue; DSCP from the DUT DSCP->TC map
# Incidental PFC: at 100% line rate on a lossless queue the DUT emits some PFC even with
# no tester pause (ingress buffer transiently hits XOFF). This allowance separates that
# background flow-control (~hundreds) from real propagation (~hundreds of thousands).
PFC_TOLERANCE_FRAMES = 10000  # "no significant PFC" allowance in the baseline phase
RATE_SAMPLE_START = 3

# Point-to-point pairs as (sender offset, receiver offset, lossless queue), indexing
# ONE leaf's tester ports (TC5 = Topology 1, single DUT). Encodes the plan's rank
# layout: rank0->rank2 on Q3, rank1->rank3 on Q4. Indexing a single leaf (not the
# global port list) keeps sender+receiver on the same DUT, so PFC propagation is
# intra-leaf. Works for single-DUT CSVs too (the lone DUT is the only "leaf").
PAIR_SPECS = [(0, 2, 3), (1, 3, 4)]

# ECN is parametrized (non_ect per plan step 3; ect_1 is the plan-update addition).
ECN_BITS = {"non_ect": "00", "ect_0": "10", "ect_1": "01", "ce": "11"}


def _conn(ack_nak_q, ecn_value, priority_to_dscp):
    return {
        "choice": "reliable_connection",
        "reliable_connection": {
            "ack": {"ip_dscp": priority_to_dscp[ack_nak_q], "ecn_value": ecn_value},
            "nak": {"ip_dscp": priority_to_dscp[ack_nak_q], "ecn_value": ecn_value},
            "enable_retransmission_timeout": True,
            "retransmission_timeout_value": 5000,
            "retransmission_retry_count": 254,
        },
    }




@pytest.mark.parametrize("phase", ["baseline", "pfc_gen"], ids=["baseline", "pfc_gen"])
# ect_1 first so the WRED-disabling cases (both non_ect cases) run last - the DUT stays
# WRED-enabled for the ect_1 cases even if a WRED restore were ever to fail.
@pytest.mark.parametrize("ecn", ["ect_1", "non_ect"], ids=["ect_1", "non_ect"])
#@pytest.mark.parametrize("phase", [ "pfc_gen"], ids=[ "pfc_gen"])
def test_rocev2_pfc_propagation(
                                request,
                                snappi_api,
                                conn_graph_facts,
                                fanout_graph_facts_multidut,
                                get_snappi_ports,
                                duthosts,
                                prio_dscp_map,
                                disable_pfcwd,
                                phase,
                                ecn,
                            ):
    """
    PFC propagation: rank0->rank2 (Q3) and rank1->rank3 (Q4), storage traffic.
    baseline expects NO DUT PFC; pfc_gen (tester pauses rank2/rank3) expects DUT
    PFC propagated upstream on Q3/Q4. Both phases: no loss/NAK. Parametrized over
    ECN: non_ect (WRED would tail-drop -> WRED disabled in pfc_gen) and ect_1 (WRED
    ECN-marks instead of dropping -> WRED left on; DUT CE-marks under congestion).
    """
    snappi_port_list = get_snappi_ports
    pytest_require(len(snappi_port_list) >= 4, "Need minimum of 4 ports")

    tconfig, plist, sports = snappi_dut_base_config(duthosts, snappi_port_list, snappi_api)
    snappi_dut_port_map = snappi_dut_port_mapping(sports)
    priority_to_dscp = derive_priority_to_dscp(prio_dscp_map)

    # TC5 is Topology 1 (single DUT): pick ONE leaf with >=4 tester ports and run the
    # point-to-point pairs within it, so PFC propagation stays intra-leaf. On a
    # single-DUT testbed the lone DUT is that leaf (uplinks/spine simply empty).
    fabric = build_fabric_map(conn_graph_facts, sports, duthosts)
    leaf = next((lf for lf in sorted(fabric.leaves)
                 if len(fabric.leaves[lf]["tester_port_ids"]) >= 4), None)
    pytest_require(leaf is not None, "TC5 needs a leaf with >=4 tester ports (single-DUT topology)")
    lp = fabric.leaves[leaf]["tester_port_ids"]      # tester port ids on this single leaf

    expect_pfc = (phase == "pfc_gen")
    duration = PAUSE_DURATION if expect_pfc else BASELINE_DURATION
    pause_bw = PAUSE_BW_PCT[ecn]          # per-ECN tester pause bandwidth
    port_cfg = {"transmit_type": "target_line_rate", "target_line_rate": LINE_RATE_PCT}
    cnp_cfg = {"ip_dscp": priority_to_dscp[CNP_QUEUE], "ecn_value": ecn}

    def tx_cfg(q):
        return {
            "mtu": IB_MTU,
            "qp_configs": [{"message_size_unit": "kb", "message_size": MSG_SIZE_KB,
                            "dscp": priority_to_dscp[q], "ecn": ecn}],
            "cnp": cnp_cfg,
            "dcqcn_settings": {"enable_dcqcn": False},   # PFC (not DCQCN) is the mechanism
            "connection_type": _conn(ACK_QUEUE, ecn, priority_to_dscp),
            "rocev2_port_config": port_cfg,
        }

    # Point-to-point topology: each sender has exactly one peer; receivers are rx-only.
    # rx_prio maps each receiver port -> the lossless priority the tester pauses on it
    # (the Q3 receiver pauses prio 3, the Q4 receiver pauses prio 4).
    topology = {}
    senders, receivers, rx_prio = [], [], {}
    for tx_off, rx_off, q in PAIR_SPECS:
        tx, rx = lp[tx_off], lp[rx_off]
        topology[tx] = {"peers": [rx], **tx_cfg(q)}
        senders.append(tx)
        receivers.append(rx)
        rx_prio[rx] = q
    for rx in receivers:
        topology[rx] = {"peers": []}

    used_lossless = sorted({q for _, _, q in PAIR_SPECS})
    lossless_dscps = [priority_to_dscp[q] for q in used_lossless]
    logger.info(f"[{phase}] PFC propagation on leaf {leaf}; "
                f"pairs={[(lp[t], lp[r], q) for t, r, q in PAIR_SPECS]} "
                f"senders={senders} receivers={receivers} lossless_qs={used_lossless}\n{topology}")

    # ---- run summary banner ----
    logger.info(
        "\n===== TC5 PFC propagation run summary =====\n"
        f"  phase           : {phase}\n"
        f"  leaf (single DUT): {leaf}\n"
        f"  pairs           : {lp[0]}->{lp[2]} (Q3), {lp[1]}->{lp[3]} (Q4)\n"
        f"  data ECN        : {ecn}  (ECN-CE bits {ECN_BITS.get(ecn, '?')})\n"
        f"  IB MTU / msg    : {IB_MTU} / {MSG_SIZE_KB} KB\n"
        f"  line rate       : {LINE_RATE_PCT}%   duration: {duration}s\n"
        f"  lossless queues : {used_lossless} -> DSCPs {lossless_dscps}\n"
        f"  ACK/NAK queue   : {ACK_QUEUE} -> DSCP {priority_to_dscp[ACK_QUEUE]}\n"
        f"  tester PFC gen  : {'ON (%d%% bw on rank%s)' % (pause_bw, receivers) if expect_pfc else 'OFF'}\n"
        f"  PFC expectation : {'PFC present (> 0)' if expect_pfc else 'no PFC (<= %d)' % PFC_TOLERANCE_FRAMES} "
        f"on {used_lossless}\n"
        "==========================================="
    )

    # Plan step 5: tester generates PFC on the receivers (pfc_gen phase only). It must
    # run AFTER set_config (which rebuilds the IxNetwork config) and BEFORE traffic
    # starts, so apply it via pre_traffic_hook (same pattern as TC7's stagger_flows).
    # The closure supplies the extra args since the hook is called as hook(api).
    pfc_hook = None
    if expect_pfc:
        def pfc_hook(api):
            generate_tester_pfc(api, rx_prio, pause_bw)

    saved_wred = None
    try:
        if ecn == "non_ect":
            # Non-ECT data is TAIL-DROPPED by WRED on the lossless egress queue (it can only
            # ECN-mark ECT). This happens in BOTH phases: in pfc_gen the tester pause builds
            # the queue, and in baseline the queue incidentally crosses the WRED threshold at
            # 100% line rate - either way non-ECT is dropped (loss/NAK/seq-errors) instead of
            # staying lossless. So disable WRED on the lossless queues for every non_ect case
            # (restored in the finally) - same approach as the pure-PFC test TC2. ECT (ect_1)
            # is ECN-MARKED (CE), not dropped, so WRED is left ON for it: the queue builds to
            # the PFC threshold, PFC propagates, and the DUT marks CE on the data.
            saved_wred = disable_wred(snappi_dut_port_map, used_lossless)

        qids = [f"UC{q}" for q in used_lossless + [ACK_QUEUE]]
        try:
            merged_df, _, _, _, _ = collect_flow_queue_stats(
                snappi_api=snappi_api, duthosts=duthosts, plist=plist, tconfig=tconfig,
                snappi_dut_port_map=snappi_dut_port_map, topology=topology,
                prio_dscp_map=prio_dscp_map, queue_ids=qids, traffic_duration=duration,
                sample_start=RATE_SAMPLE_START, config_name=request.node.name,
                pre_traffic_hook=pfc_hook)
        except NotImplementedError as e:
            pytest.skip(f"TC5 pfc_gen phase pending tester PFC generation: {e}")
        # PFC from the authoritative DUT counters (snappi Rx-pause stat unreliable).
        # Rx = did the tester pause reach the DUT; Tx = did the DUT propagate upstream.
        rx_pfc_df = pfc_counters(snappi_dut_port_map, direction="Rx")
        logger.info(f"[{phase}] DUT Rx PFC counters (tester pause received by the DUT):\n"
                    f"{tabulate(rx_pfc_df, headers='keys', tablefmt='psql')}")
        pfc_df = pfc_counters(snappi_dut_port_map, direction="Tx")
        logger.info(f"[{phase}] DUT Tx PFC counters (DUT propagating upstream):\n"
                    f"{tabulate(pfc_df, headers='keys', tablefmt='psql')}")
        pfc_cols = [f"PFC{q}" for q in used_lossless if f"PFC{q}" in pfc_df.columns]
        pytest_assert(len(pfc_cols) == len(used_lossless),
                      f"Missing DUT PFC counter column(s) for lossless priorities {used_lossless}; "
                      f"have {list(pfc_df.columns)}")
        pfc_totals = {c: int(pd.to_numeric(pfc_df[c], errors="coerce").fillna(0).sum()) for c in pfc_cols}
        pfc_sum_df = pd.DataFrame([pfc_totals])

        # ---- checks ----
        checks = [
            make_check(f"ip_dscp in {lossless_dscps} and (message_fail != 0 or frame_delta != 0)",
                    ["flow_name", "port_tx", "port_rx", "ip_dscp", "message_tx",
                     "message_complete_rx", "message_fail", "frame_delta"],
                    "Lossless: all messages complete, no loss",
                    f"message_fail == 0 and frame_delta == 0 required for lossless DSCPs {lossless_dscps}"),
            make_check(f"ip_dscp in {lossless_dscps} and (nak_tx != 0 or nak_rx != 0 or frame_sequence_error != 0)",
                    ["flow_name", "port_tx", "port_rx", "ip_dscp", "nak_tx", "nak_rx", "frame_sequence_error"],
                    "Lossless: no NAK/sequence errors",
                    f"nak_tx=0 & nak_rx=0 & frame_sequence_error=0 required for lossless DSCPs {lossless_dscps}"),
        ]
        if ecn == "non_ect":
            # Non-ECT transport is not ECN-capable, so the DUT must never CE-mark the data.
            checks.append(make_check(
                    f"ip_dscp in {lossless_dscps} and ecn_ce_rx != 0",
                    ["flow_name", "port_tx", "port_rx", "ip_dscp", "ecn_ce_rx"],
                    "Non-ECT: no ECN-CE marking",
                    f"ecn_ce_rx == 0 required for non-ECT lossless DSCPs {lossless_dscps}"))
        elif expect_pfc:  # ect_1 + pfc_gen: the heavy tester pause (pause_bw=10) drives the
            # egress queue past the WRED/ECN threshold, so the DUT MUST CE-mark the ECT data
            # (validated: ~342M marks). ecn_ce_rx == 0 on a lossless flow => marking failed.
            # NOTE: this assumes the ect_1 pause stays heavy enough to cross the ECN threshold;
            # lightening PAUSE_BW_PCT["ect_1"] would reduce/remove marking and trip this check.
            checks.append(make_check(
                    f"ip_dscp in {lossless_dscps} and ecn_ce_rx == 0",
                    ["flow_name", "port_tx", "port_rx", "ip_dscp", "ecn_ce_rx"],
                    "ect_1: ECN-CE marking present under congestion",
                    f"ecn_ce_rx > 0 required for ect_1 lossless DSCPs {lossless_dscps} under tester-pause congestion"))
        if expect_pfc:
            pfc_fail_expr = " or ".join(f"{c} == 0" for c in pfc_cols)
            checks.append(make_check(pfc_fail_expr, list(pfc_sum_df.columns),
                    f"PFC propagated on lossless priority {used_lossless}",
                    f"DUT Tx PFC expected (> 0) on {used_lossless} when tester pauses the receivers",
                    override_df=pfc_sum_df))
        else:
            pfc_fail_expr = " or ".join(f"{c} > {PFC_TOLERANCE_FRAMES}" for c in pfc_cols)
            checks.append(make_check(pfc_fail_expr, list(pfc_sum_df.columns),
                    f"No PFC on lossless priority {used_lossless} (baseline)",
                    f"DUT Tx PFC must be <= {PFC_TOLERANCE_FRAMES} on {used_lossless} with no tester pause",
                    override_df=pfc_sum_df))

        assert_queries(merged_df, checks)
        logger.info(f"*** TC5 PFC propagation [{phase}] PASSED ***")
    finally:
        if expect_pfc:
            clear_tester_pfc(snappi_api)
        if saved_wred:
            restore_wred(saved_wred)
        start_stop(snappi_api, operation="stop", op_type="traffic", wait_convergence=False)
        start_stop(snappi_api, operation="stop", op_type="protocols")
